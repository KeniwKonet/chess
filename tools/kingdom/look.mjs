// Quick visual check of Chess Kingdom: home, setup, start vs AI, a few moves with their scenes.
import { chromium } from '@playwright/test';
const S = process.env.OUT ?? '.';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
const page = await b.newPage({ viewport: { width: Number(process.env.W ?? 1280), height: Number(process.env.H ?? 800) } });
const logs = [];
page.on('pageerror', (e) => logs.push('ERR ' + e.message));
page.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') logs.push(m.type() + ' ' + m.text().slice(0, 300)); });
await page.goto(process.env.URL ?? 'http://localhost:4174/');
await page.waitForSelector('body[data-ready="1"]', { timeout: 120000 });
await page.waitForSelector('body[data-pieces="1"]', { timeout: 120000 }).catch(() => logs.push('pieces never ready'));
await page.waitForTimeout(2500);
await page.screenshot({ path: `${S}/k-home.png` });
await page.getByRole('button', { name: /Play the computer/ }).click();
await page.waitForTimeout(500);
await page.screenshot({ path: `${S}/k-setup.png` });
await page.getByRole('button', { name: 'To battle' }).click();
await page.waitForTimeout(1500);
await page.evaluate(() => window.__crKingdom.settleCamera());
await page.waitForTimeout(1500);
await page.screenshot({ path: `${S}/k-start.png` });
const tap = async (sq) => { const p = await page.evaluate((s) => window.__crKingdom.project(s), sq); await page.mouse.click(p.x, p.y); await page.waitForTimeout(400); };
await tap('g1');
await page.waitForTimeout(500);
await page.screenshot({ path: `${S}/k-select.png` });
await tap('f3');
await page.waitForTimeout(1500);
await page.screenshot({ path: `${S}/k-leap.png` });
await page.waitForFunction(() => window.__crKingdom.kc.game.history.length >= 2, null, { timeout: 60000 }).catch(() => logs.push('AI never replied'));
await page.waitForTimeout(3500);
await page.screenshot({ path: `${S}/k-reply.png` });
console.log(JSON.stringify({ history: await page.evaluate(() => window.__crKingdom.kc.game.history.map((m) => m.san)), logs: logs.slice(0, 12) }, null, 1));
await b.close();
